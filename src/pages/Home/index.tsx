import React, { useState } from 'react';
import {
  Accordion,
  AccordionDetails,
  AccordionSummary,
  Box,
  Button,
  Container,
  Grid,
  Link,
  styled,
  Typography,
} from '@mui/material';
import {
  AutoAwesome,
  Code,
  Devices,
  EmojiEvents,
  ExpandMore,
  FileDownload,
  Groups,
  RocketLaunch,
} from '@mui/icons-material';
