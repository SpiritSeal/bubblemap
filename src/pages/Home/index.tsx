const faqJsonLd = {
  '@context': 'https://schema.org',
  '@type': 'FAQPage',
  mainEntity: faqs.map(({ question, answer }) => ({
    '@type': 'Question',
    name: question,
    acceptedAnswer: { '@type': 'Answer', text: answer },
  })),
};

const SectionHeading = ({ children }: { children: React.ReactNode }) => (
  <Typography
    variant="h4"
    component="h2"
    align="center"
    sx={{ mb: { xs: 3, md: 5 } }}
  >
    {children}
  </Typography>
);

const HomePage = () => {
  const auth = useAuth();
  const firestore = useFirestore();
  const navigate = useNavigate();
  const signInCheck = useSigninCheck().data;
  const [creating, setCreating] = useState(false);

  const mindmapsCollection = collection(firestore, 'mindmaps');

  const createMindMap = (title: string, user: UserCredential) => {
    const newDocData: MindMap = {
      metadata: {
        createdAt: serverTimestamp() as Timestamp,
        createdBy: user.user.uid,
        updatedAt: serverTimestamp() as Timestamp,
        updatedBy: user.user.uid,
        everUpdatedBy: [user.user.uid],
      },
      nodes: [createRootNode(title)],
      permissions: {
        owner: user.user.uid,
        canPublicEdit: false,
        isPublic: false,
      },
      title,
    };
    addDoc(mindmapsCollection, newDocData).then((newDoc) => {
      navigate(`/mindmaps/${newDoc.id}`);
    });
  };

  const primaryCta = !signInCheck.user ? (
    <Button
      onClick={() => {
        setCreating(true);
        signInAnonymously(auth)
          .then((user) => createMindMap('Untitled MindMap', user))
          .catch(() => {
            setCreating(false);
          });
      }}
      disabled={creating}
      variant="contained"
      size="large"
    >
      Create Your First MindMap
    </Button>
  ) : (
    <Button
      onClick={() => navigate('/mindmaps')}
      variant="contained"
      size="large"
    >
      Browse Your Mindmaps
    </Button>
  );

  return (
    <Box component="main">
      <script
        type="application/ld+json"
        // eslint-disable-next-line react/no-danger
        dangerouslySetInnerHTML={{ __html: JSON.stringify(faqJsonLd) }}
      />

      <Content maxWidth="md">
        <Logo src="/assets/logos/Bubble Map Logo.svg" alt="Bubble Map logo" />
        <div>
          <Title>Bubble Map</Title>
          <Typography
            variant="h4"
            component="p"
            color="inherit"
            style={{ fontWeight: 'bold' }}
          >
            Free, AI-Assisted
            <br /> <b>Mind Mapping</b>
          </Typography>
          <Typography
            variant="body1"
            color="text.secondary"
            sx={{ mt: 2, maxWidth: '36rem' }}
          >
            Brainstorm on an infinite canvas: grow ideas bubble by bubble,
            invite others to edit live, and let AI suggest your next idea when
            you are stuck. Nothing to install — it runs in your browser on
            desktop and mobile.
          </Typography>
          <Box sx={{ mt: 3 }}>{primaryCta}</Box>
          <Typography
            variant="body2"
            color="text.secondary"
            sx={{
              mt: 2,
              display: 'flex',
              alignItems: 'center',
              gap: 1,
              justifyContent: { xs: 'center', md: 'flex-start' },
            }}
          >
            <EmojiEvents fontSize="small" aria-hidden />
            Winner of the 2022 Congressional App Challenge (AZ-06)
          </Typography>
        </div>
      </Content>

      <Container
        component="section"
        maxWidth="md"
        sx={{ py: { xs: 6, md: 8 } }}
      >
        <SectionHeading>Everything you need to think visually</SectionHeading>
        <Grid container spacing={4}>
          {features.map(({ icon, title, text }) => (
            <Grid key={title} size={{ xs: 12, sm: 6, md: 4 }}>
              <Box
                aria-hidden
                sx={{
                  width: 48,
                  height: 48,
                  borderRadius: '50%',
                  display: 'flex',
                  alignItems: 'center',
                  justifyContent: 'center',
                  bgcolor: 'primary.main',
                  color: 'primary.contrastText',
                  mb: 1.5,
                }}
              >
                {icon}
              </Box>
              <Typography variant="h6" component="h3" sx={{ mb: 0.5 }}>
                {title}
              </Typography>
              <Typography variant="body2" color="text.secondary">
                {text}
              </Typography>
            </Grid>
          ))}
        </Grid>
      </Container>

      <Container
        component="section"
        maxWidth="md"
        sx={{ py: { xs: 6, md: 8 } }}
      >
        <SectionHeading>How it works</SectionHeading>
        <Grid container spacing={4}>
          {steps.map(({ title, text }, index) => (
            <Grid key={title} size={{ xs: 12, md: 4 }}>
              <Box
                aria-hidden
                sx={{
                  width: 40,
                  height: 40,
                  borderRadius: '50%',
                  display: 'flex',
                  alignItems: 'center',
                  justifyContent: 'center',
                  border: 2,
                  borderColor: 'primary.main',
                  color: 'primary.main',
                  fontWeight: 'bold',
                  mb: 1.5,
                }}
              >
                {index + 1}
              </Box>
              <Typography variant="h6" component="h3" sx={{ mb: 0.5 }}>
                {title}
              </Typography>
              <Typography variant="body2" color="text.secondary">
                {text}
              </Typography>
            </Grid>
          ))}
        </Grid>
      </Container>

      <Container
        component="section"
        maxWidth="md"
        sx={{ py: { xs: 6, md: 8 } }}
      >
        <SectionHeading>Frequently asked questions</SectionHeading>
        {faqs.map(({ question, answer }) => (
          <Accordion key={question} variant="outlined" disableGutters>
            {/* AccordionSummary already renders inside an <h3> heading. */}
            <AccordionSummary expandIcon={<ExpandMore />}>
              <Typography variant="body1" sx={{ fontWeight: 'bold' }}>
                {question}
              </Typography>
            </AccordionSummary>
            <AccordionDetails>
              <Typography variant="body2" color="text.secondary">
                {answer}
                {question === 'Is my data private?' && (
                  <>
                    {' '}
                    <Link component={RouterLink} to="/privacy" color="inherit">
                      Read the privacy policy
                    </Link>
                    .
                  </>
                )}
              </Typography>
            </AccordionDetails>
          </Accordion>
        ))}
      </Container>

      <Container
        component="section"
        maxWidth="md"
        sx={{ py: { xs: 6, md: 8 }, textAlign: 'center' }}
      >
        <Typography variant="h4" component="h2" sx={{ mb: 2 }}>
          Ready to map your ideas?
        </Typography>
        <Typography variant="body1" color="text.secondary" sx={{ mb: 3 }}>
          Your first mind map is one click away — free, no account required.
        </Typography>
        {primaryCta}
      </Container>
    </Box>
  );
};

export default HomePage;
